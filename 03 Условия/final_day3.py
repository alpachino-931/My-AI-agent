# Задание 21. Система проверки заявки

name = input("Введите имя участника: ")
age = int(input("Введите возраст: "))
course = input("Введите курс: ")
consent = input("Согласие на участие? да/нет: ")
score = int(input("Введите тестовый балл от 0 до 100: "))

if age < 16:
    result = "Возраст не подходит"
elif consent != "да":
    result = "Нет согласия на участие"
elif score >= 90:
    result = "Высокий результат"
elif score >= 70:
    result = "Хороший результат"
elif score >= 50:
    result = "Допустимый результат"
else:
    result = "Результат недостаточен"

print("========================================")
print("        ПРОВЕРКА ЗАЯВКИ")
print("========================================")
print("Имя участника:", name)
print("Курс:", course)
print("Тестовый балл:", score)
print("Результат проверки:", result)

if age < 16 or consent != "да":
    print("Итог: заявка отклонена")
else:
    print("Итог: заявка допущена к участию")
