# Задание 30. Таблица результатов
import pandas as pd

data = {
    "Имя": ["Артем", "Анна", "Олег", "Мария", "Иван", "Полина"],
    "Группа": ["1ИИ-1", "1ИИ-1", "1ИИ-2", "1ИИ-2", "1ИИ-1", "1ИИ-2"],
    "Баллы": [85, 72, 91, 64, 78, 88],
}

df = pd.DataFrame(data)

print(df)
print("Средний балл:", df["Баллы"].mean())
print("Баллы 80 и выше:")
print(df[df["Баллы"] >= 80])
print("Группа 1ИИ-2:")
print(df[df["Группа"] == "1ИИ-2"])
print(df.head(3))
print(df.tail(2))
