# Задание 29. Таблица товаров
import pandas as pd

data = {
    "Товар": ["Ноутбук", "Мышь", "Клавиатура", "Монитор", "Наушники"],
    "Цена": [65000, 1200, 3500, 18000, 2500],
    "Количество": [3, 15, 8, 5, 10],
}

df = pd.DataFrame(data)
df["Стоимость"] = df["Цена"] * df["Количество"]

print(df)
print("Средняя цена:", df["Цена"].mean())
print("Самая низкая цена:", df["Цена"].min())
print("Самая высокая цена:", df["Цена"].max())
print("Товары дороже 3000:")
print(df[df["Цена"] > 3000])
