# Задание 19. Основные показатели
import pandas as pd

data = {
    "Имя": ["Артем", "Анна", "Олег", "Мария"],
    "Баллы": [85, 72, 91, 64],
}

df = pd.DataFrame(data)

print("Сумма:", df["Баллы"].sum())
print("Среднее:", df["Баллы"].mean())
print("Минимум:", df["Баллы"].min())
print("Максимум:", df["Баллы"].max())
