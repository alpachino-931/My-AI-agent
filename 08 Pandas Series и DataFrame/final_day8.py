# Задание 32. Анализ учебной группы в Pandas
import pandas as pd

data = {
    "Имя": ["Артем", "Анна", "Олег", "Мария", "Иван", "Полина", "Дмитрий", "Алина"],
    "Группа": ["1ИИ-1", "1ИИ-1", "1ИИ-2", "1ИИ-2", "1ИИ-1", "1ИИ-2", "1ИИ-1", "1ИИ-2"],
    "Баллы": [85, 72, 91, 64, 78, 88, 59, 95],
    "Посещено занятий": [18, 15, 20, 12, 17, 19, 10, 20],
}

df = pd.DataFrame(data)
df["Баллы после бонуса"] = df["Баллы"] + 5

print("=" * 40)
print("Исходная таблица:")
print(df)

print("=" * 40)
print("shape:", df.shape)
print("columns:", list(df.columns))

print("=" * 40)
print("Первые 3 строки:")
print(df.head(3))
print("Последние 2 строки:")
print(df.tail(2))

print("=" * 40)
print("Средний балл:", df["Баллы"].mean())
print("Минимальный балл:", df["Баллы"].min())
print("Максимальный балл:", df["Баллы"].max())
print("Сумма посещенных занятий:", df["Посещено занятий"].sum())

print("=" * 40)
print("Баллы 80 и выше:")
print(df[df["Баллы"] >= 80])
print("Группа 1ИИ-1:")
print(df[df["Группа"] == "1ИИ-1"])
print("Баллы от 60 до 80:")
print(df[(df["Баллы"] >= 60) & (df["Баллы"] <= 80)])

print("=" * 40)
print("Столбцы Имя и Баллы:")
print(df[["Имя", "Баллы"]])

print("=" * 40)
print("Строка loc[0]:")
print(df.loc[0])
print("Строка iloc[1]:")
print(df.iloc[1])
print("=" * 40)
